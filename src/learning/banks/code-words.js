// Authored items for word-based verbal reasoning (Code zone, Year 3 Autumn):
// synonyms, antonyms, odd one out and compound words. Item ids are stable
// (they're in the learning log). `level` 1–3 is how hard the vocabulary is.
// Every item is checked against the separate relations lexicon in
// check/relations.js, so a wrong option that is secretly also right is caught.
// In wrong-option lists, '!' marks the opposite of the word (synonym items)
// and '=' a word that means the same (antonym items): they choose which
// misconception is explained, and a test checks them against the lexicon.
import { registerIds } from '../ids.js';

const S = (word, answer, wrong, level = 1) => ({ id: `syn.${word}`, word, answer, wrong, level });
const A = (word, answer, wrong, level = 1) => ({ id: `ant.${word}`, word, answer, wrong, level });
const O = (id, group, words, odd, level = 1) => ({ id: `odd.${id}`, group, words, odd, level });
const C = (first, answer, wrong, level = 1) => ({ id: `cmp.${first}${answer}`, first, answer, wrong, level });

