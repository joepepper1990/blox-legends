// Keeps src/learning/ids-lock.js up to date. Every id that ever reaches a
// save or the learning log is recorded there forever: tests fail if an id
// disappears (unless it's listed as retired, with its successor) or if a new
// id appears without being locked.
//
//   node tools/ids-lock.mjs          add any new ids to the lock
//   node tools/ids-lock.mjs --check  exit 1 if the lock is out of date
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { currentIds } from '../src/learning/ids.js';
import { IDS_LOCK } from '../src/learning/ids-lock.js';

const file = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'learning', 'ids-lock.js');
const now = currentIds();
const next = { retired: IDS_LOCK.retired || {} };
let added = 0;
for (const [kind, ids] of Object.entries(now)) {
  const old = IDS_LOCK[kind] || [];
  const merged = [...new Set([...old, ...ids])].sort();
  added += merged.length - old.length;
  next[kind] = merged;
}
for (const kind of Object.keys(IDS_LOCK)) if (!(kind in next)) next[kind] = IDS_LOCK[kind];

if (process.argv.includes('--check')) {
  if (added) {
    console.error(`${added} new id(s) are not in the lock. Run: node tools/ids-lock.mjs`);
    process.exit(1);
  }
  console.log('ids lock is up to date');
} else {
  const body = Object.entries(next)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v, null, 2).replace(/\n/g, '\n  ')},`)
    .join('\n');
  writeFileSync(
    file,
    `// GENERATED by tools/ids-lock.mjs — every id that has ever been issued.\n// Never delete an entry: retire it instead (retired: { oldId: successorId }).\nexport const IDS_LOCK = {\n${body}\n};\n`,
  );
  console.log(`ids lock updated (+${added})`);
}
