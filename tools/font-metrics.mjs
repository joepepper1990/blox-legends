// Measures Lexend Bold glyph advances in a real browser and writes
// src/engine/font-metrics.js, so label and door fit can be checked in Node
// (tools/validate-content.mjs) without a canvas. Re-run if the font changes;
// tests/e2e checks the table still matches the font.
import { writeFileSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHARS = [...new Set(" ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789?!.,:;'’-−+×÷=<>()→↔_…/&@£%\"".split(''))];
const font = readFileSync(join(root, 'fonts', 'lexend-latin-700-normal.woff2')).toString('base64');
const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent(`<style>@font-face{font-family:Lexend;font-weight:700;src:url(data:font/woff2;base64,${font}) format('woff2')}</style><div style="font-family:Lexend;font-weight:700">x</div>`);
const widths = await page.evaluate(async (chars) => {
  await document.fonts.load("700 100px 'Lexend'");
  const c = document.createElement('canvas').getContext('2d');
  c.font = "700 1000px 'Lexend'";
  return Object.fromEntries(chars.map((ch) => [ch, Math.round(c.measureText(ch).width) / 1000]));
}, CHARS);
await browser.close();
writeFileSync(
  join(root, 'src', 'engine', 'font-metrics.js'),
  `// GENERATED by tools/font-metrics.mjs — Lexend Bold advance widths in em.
export const LEXEND_700 = ${JSON.stringify(widths)};
const FALLBACK = 1; // at least as wide as the widest measured glyph (W)

// Width in em of a string drawn with extra letter spacing (in em).
export function textEm(text, spacingEm = 0) {
  const s = String(text);
  let w = 0;
  for (const ch of s) w += LEXEND_700[ch] ?? FALLBACK;
  return w + spacingEm * Math.max(0, s.length - 1);
}
`,
);
console.log('font metrics written', Object.keys(widths).length, 'glyphs; W =', widths.W, 'i =', widths.i);
